import crypto from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build, version as esbuildVersion } from 'esbuild';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = resolve(dirname(SCRIPT_PATH), '..');
const PROFILE = 'conformance/composition/ccs-v14-aeb-github-v0.1';
const ENTRY = `${PROFILE}/run.mjs`;
const OUTPUT = `${PROFILE}/run.standalone.mjs`;
const MANIFEST = `${PROFILE}/standalone.manifest.json`;
const NOTICES = `${PROFILE}/THIRD_PARTY_NOTICES.txt`;
const SUPPORT_FILES = [
  `${PROFILE}/upstream-01-allow.receipt.json`,
  `${PROFILE}/report.reference.json`,
  `${PROFILE}/vectors.reference.json`,
];
const THIRD_PARTY_COMPONENTS = [
  {
    names: ['@noble/curves', '@noble/hashes'],
    version: '2.3.0',
    packageFiles: [
      'node_modules/@noble/curves/package.json',
      'node_modules/@noble/curves/node_modules/@noble/hashes/package.json',
      'node_modules/@noble/post-quantum/node_modules/@noble/hashes/package.json',
    ],
    licenseFile: 'node_modules/@noble/curves/LICENSE',
  },
  {
    names: ['@noble/post-quantum'],
    version: '0.7.0',
    packageFiles: ['node_modules/@noble/post-quantum/package.json'],
    licenseFile: 'node_modules/@noble/post-quantum/LICENSE',
  },
];
const BANNER = [
  '// SPDX-License-Identifier: Apache-2.0',
  '// Generated by scripts/build-ccs-v14-aeb-standalone.mjs. Do not edit.',
].join('\n');

function sha256(content) {
  return crypto.createHash('sha256').update(content).digest('hex');
}

async function fileDigest(relativePath) {
  return sha256(await readFile(resolve(ROOT, relativePath)));
}

async function renderThirdPartyNotices() {
  const sections = [];
  for (const component of THIRD_PARTY_COMPONENTS) {
    for (const packageFile of component.packageFiles) {
      const packageJson = JSON.parse(await readFile(resolve(ROOT, packageFile), 'utf8'));
      if (packageJson.version !== component.version) {
        throw new Error(
          `${packageFile} version ${packageJson.version} does not match notice pin ${component.version}`,
        );
      }
    }
    const packages = component.names
      .map((name) => `- ${name} ${component.version}`)
      .join('\n');
    const license = (await readFile(resolve(ROOT, component.licenseFile), 'utf8')).trimEnd();
    sections.push(`${packages}\n\n${license}`);
  }
  return [
    'Third-Party Notices',
    '===================',
    '',
    'The standalone runner includes portions of these MIT-licensed packages:',
    '',
    sections.join('\n\n---\n\n'),
    '',
  ].join('\n');
}

async function render() {
  const notices = await renderThirdPartyNotices();
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [ENTRY],
    outfile: OUTPUT,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    charset: 'utf8',
    legalComments: 'inline',
    sourcemap: false,
    metafile: true,
    write: false,
    banner: { js: BANNER },
  });
  if (result.outputFiles.length !== 1) {
    throw new Error(`expected one standalone output, received ${result.outputFiles.length}`);
  }

  const bundle = result.outputFiles[0].contents;
  const inputs = {};
  for (const input of Object.keys(result.metafile.inputs).sort()) {
    inputs[input] = await fileDigest(input);
  }
  const supportFiles = {};
  for (const filename of SUPPORT_FILES) {
    supportFiles[filename.slice(PROFILE.length + 1)] = await fileDigest(filename);
  }
  supportFiles[NOTICES.slice(PROFILE.length + 1)] = sha256(notices);
  const manifest = `${JSON.stringify({
    '@version': 'CCS-V1.4-AEB-GITHUB-STANDALONE-MANIFEST-v1',
    entrypoint: 'run.standalone.mjs',
    entrypoint_sha256: sha256(bundle),
    node_requirement: '>=20.19.0',
    generator: {
      script: 'scripts/build-ccs-v14-aeb-standalone.mjs',
      esbuild_version: esbuildVersion,
    },
    source_inputs: inputs,
    support_files: supportFiles,
    third_party: THIRD_PARTY_COMPONENTS.map(({ names, version, licenseFile }) => ({
      packages: names,
      version,
      license_file: licenseFile,
    })),
  }, null, 2)}\n`;
  return { bundle, manifest, notices };
}

async function sync({ check }) {
  const expected = await render();
  const targets = [
    [OUTPUT, expected.bundle],
    [NOTICES, expected.notices],
    [MANIFEST, expected.manifest],
  ];
  for (const [relativePath, content] of targets) {
    const absolutePath = resolve(ROOT, relativePath);
    if (check) {
      let actual = null;
      try {
        actual = await readFile(absolutePath);
      } catch (error) {
        if (error?.code !== 'ENOENT') throw error;
      }
      const expectedBytes = typeof content === 'string' ? Buffer.from(content) : content;
      if (actual === null || !actual.equals(expectedBytes)) {
        throw new Error(`${relativePath} is missing or stale; run npm run build:ccs-v14-aeb-standalone`);
      }
    } else {
      await writeFile(absolutePath, content);
    }
  }
  process.stdout.write(
    `CCS v1.4 + AEB standalone: ${check ? 'synchronized' : 'generated'} (${sha256(expected.bundle)})\n`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_PATH) {
  await sync({ check: process.argv.includes('--check') });
}
